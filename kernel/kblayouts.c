uint32_t kb_compose(uint32_t acc, uint32_t base) {
    if (acc == '\'') acc = 0xB4;                     /* (US International's ' and ": ´ and ¨) */
    else if (acc == '"') acc = 0xA8;
    for (int i = 0; i < N(COMPOSE); i++)
        if (COMPOSE[i].acc == acc && COMPOSE[i].base == base) return COMPOSE[i].out;
    return 0;
}
